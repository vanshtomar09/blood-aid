CREATE TABLE blood_banks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    location     VARCHAR(200) NOT NULL,
    latitude     DOUBLE PRECISION NOT NULL,
    longitude    DOUBLE PRECISION NOT NULL,
    distance_km  DOUBLE PRECISION,
    phone        VARCHAR(40),
    email        VARCHAR(160),
    open_hours   VARCHAR(80)
);

CREATE TABLE blood_inventory (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id     BIGINT NOT NULL REFERENCES blood_banks (id) ON DELETE CASCADE,
    blood_type  VARCHAR(3) NOT NULL,
    units       INTEGER NOT NULL,
    CONSTRAINT uq_inventory_bank_type UNIQUE (bank_id, blood_type),
    CONSTRAINT ck_inventory_type CHECK (blood_type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    CONSTRAINT ck_inventory_units CHECK (units >= 0)
);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(20) NOT NULL,
    blood_type     VARCHAR(3),
    phone          VARCHAR(40),
    employee_id    VARCHAR(60),
    bank_id        BIGINT REFERENCES blood_banks (id) ON DELETE SET NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('DONOR', 'RECIPIENT', 'STAFF', 'ADMIN'))
);

CREATE TABLE blood_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name    VARCHAR(120) NOT NULL,
    contact_number  VARCHAR(40) NOT NULL,
    blood_type      VARCHAR(3) NOT NULL,
    units           INTEGER NOT NULL,
    urgency         VARCHAR(20) NOT NULL,
    hospital_name   VARCHAR(200) NOT NULL,
    notes           VARCHAR(1000),
    status          VARCHAR(20) NOT NULL,
    requester_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_requests_type CHECK (blood_type IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    CONSTRAINT ck_requests_units CHECK (units > 0),
    CONSTRAINT ck_requests_urgency CHECK (urgency IN ('ROUTINE', 'URGENT', 'EMERGENCY')),
    CONSTRAINT ck_requests_status CHECK (status IN ('PENDING', 'IN_PROGRESS', 'FULFILLED'))
);

CREATE INDEX idx_requests_created ON blood_requests (created_at DESC);
CREATE INDEX idx_requests_status ON blood_requests (status);
CREATE INDEX idx_requests_requester ON blood_requests (requester_id);

CREATE TABLE donation_camps (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(160) NOT NULL,
    location   VARCHAR(200),
    camp_date  DATE NOT NULL
);
